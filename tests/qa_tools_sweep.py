def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(cmd):
    return subprocess.run(cmd, capture_output=True, check=True, timeout=120)


def probe(path):
    return json.loads(
        run(
            [
                "ffprobe",
                "-v",
                "error",
                "-show_streams",
                "-show_format",
                "-of",
                "json",
                str(path),
            ]
        ).stdout
    )


def duration(path):
    return float(probe(path)["format"]["duration"])


def pcm(path):
    raw = run(
        [
            "ffmpeg",
            "-v",
            "error",
            "-i",
            str(path),
            "-vn",
            "-ac",
            "1",
            "-ar",
            "16000",
            "-f",
            "f32le",
            "-",
        ]
    ).stdout
    samples = array.array("f")
    samples.frombytes(raw)
    return samples


def rms(samples):
    return math.sqrt(sum(x * x for x in samples) / max(1, len(samples)))


def near(actual, expected, tolerance=0.18):
    assert abs(actual - expected) <= tolerance, f"{actual} != {expected} +/- {tolerance}"


def inventory():
    cells = []
    keys = sorted({key for row in REGISTRY for key in row.inputs})
    for key in keys:
        for count in (1, 2):
            names = [f"synthetic {n}{key}" for n in range(count)]
            sections = files_listing(names)[0][1]
            assert [tid for tid, _ in sections["tools"]] == tools_for(
                names[0], count == 2
            )
            for kind in ("tools", "actions"):
                for ident, _ in sections[kind]:
                    cells.append(
                        {
                            "id": f"{kind}:{ident}:{key}:{count}",
                            "kind": kind,
                            "operation_id": ident,
                            "source_key": key,
                            "selection_count": count,
                        }
                    )
    assert {c["operation_id"] for c in cells if c["kind"] == "tools"} == set(TOOLS)
    assert {c["operation_id"] for c in cells if c["kind"] == "actions"} == set(ACTIONS)
    assert len({c["id"] for c in cells}) == len(cells)
    return cells


def prepare(root):
    fixtures, errors = build_fixtures(root)
    # Richer tool corpus: real embedded tags, stereo, high-quality compressible media.
    # All files here were just generated by us, never supplied by the user.
    for key in IMAGE_KEYS & fixtures.keys():
        im = Image.new("RGB", (96, 64), "red")
        im.paste("blue", (48, 0, 96, 64))
        exif = Image.Exif()
        exif[315] = "Synthetic private artist"
        kwargs = {"exif": exif} if key != ".bmp" else {}
        if key in {".jpg", ".jpeg", ".webp", ".heic", ".heif", ".avif"}:
            kwargs["quality"] = 98
        im.save(fixtures[key], **kwargs)
    for key in (AUDIO_KEYS | VIDEO_KEYS) & fixtures.keys():
        if key == ".gif":
            frames = [
                Image.new("RGB", (160, 120), color) for color in ("red", "blue", "green")
            ]
            frames[0].save(
                fixtures[key],
                save_all=True,
                append_images=frames[1:],
                duration=400,
                loop=0,
                comment=b"Synthetic private title",
            )
            continue
        cmd = ["ffmpeg", "-y", "-v", "error", "-f", "lavfi"]
        if key in VIDEO_KEYS:
            cmd += ["-i", "testsrc2=duration=1.2:size=160x120:rate=20", "-f", "lavfi"]
        cmd += ["-i", "sine=frequency=440:duration=1.2", "-ac", "2"]
        if key in VIDEO_KEYS:
            codecs = {
                ".webm": ["-c:v", "libvpx-vp9", "-c:a", "libopus", "-b:v", "500k"],
                ".wmv": ["-c:v", "wmv2", "-c:a", "wmav2", "-b:v", "500k"],
            }
            cmd += codecs.get(key, ["-c:v", "libx264", "-crf", "10", "-c:a", "aac"])
        if key in AUDIO_KEYS:
            cmd += ["-af", "volume=0.1"]
        cmd += ["-metadata", "title=Synthetic private title", str(fixtures[key])]
        run(cmd)
    with fitz.open(fixtures[".pdf"]) as doc:
        doc.set_metadata(
            {"author": "Synthetic private author", "title": "Synthetic private title"}
        )
        doc.set_xml_metadata("<private>Synthetic private XML</private>")
        doc.saveIncr()
    return fixtures, errors


def image_effect(tool, src, out):
    with Image.open(src) as before, Image.open(out) as after:
        before.load()
        after.load()
        expected = {
            "compress": (48, 32),
            "cropImage": (48, 64),
            "frameImage": (176, 144),
        }.get(tool, (96, 64))
        assert after.size == expected, f"dimensions {after.size} != {expected}"
        a, b = after.convert("RGB"), before.convert("RGB")
        evidence = {"dimensions": list(after.size), "decoded": True}
        if tool == "removeMetadata":
            assert not after.getexif().get(315), "Artist survived"
            if src.suffix.lower() != ".bmp":
                assert before.getexif().get(315), "fixture has no Artist tag"
            assert abs(ImageStat.Stat(a).mean[0] - ImageStat.Stat(b).mean[0]) < 10
            evidence["artist_removed"] = src.suffix.lower() != ".bmp"
        elif tool == "cropImage":
            pixel = a.getpixel((20, 20))
            assert pixel[2] > 200 and pixel[0] < 20, f"wrong crop region {pixel}"
        elif tool == "frameImage":
            assert min(a.getpixel((0, 0))) > 245
            assert a.getpixel((60, 60))[0] > 200
        elif tool == "redactImage":
            assert max(a.getpixel((20, 20))) < 10
            assert a.getpixel((70, 20))[2] > 200
        elif tool == "editImage":
            assert 110 < a.getpixel((20, 20))[0] < 145
        elif tool == "annotateImage":
            assert ImageChops.difference(a, b).getbbox() is not None, (
                "annotation changed no pixels"
            )
        return evidence


def pdf_effect(tool, srcs, paths):
    expected = ["Kumquat page 1 - 42", "Kumquat page 2 - 42"]
    texts = []
    for out in paths:
        with fitz.open(out) as doc:
            texts.extend(p.get_text().strip().splitlines()[0] for p in doc)
            assert all(p.rect.width == 720 and p.rect.height == 405 for p in doc)
            assert all(len(set(p.get_pixmap().samples)) > 1 for p in doc)
            if tool == "removeMetadata":
                assert not doc.metadata.get("author") and not doc.get_xml_metadata()
                assert b"Synthetic private" not in out.read_bytes()
    wanted = list(reversed(expected)) if tool == "organizePDF" else expected * len(srcs)
    assert texts == wanted, f"wrong pages/order: {texts}"
    if tool == "compress":
        assert all(
            p.stat().st_size < s.stat().st_size for p, s in zip(paths, srcs, strict=True)
        )
    return {"page_texts": texts, "page_geometry_preserved": True}


def video_effect(tool, srcs, paths):
    source = srcs[0]
    before = probe(source)
    expected_duration = (
        0.6 if tool in {"trimVideo", "splitVideo", "changeVideoSpeed"} else 1.2
    )
    if tool == "joinVideos":
        expected_duration *= len(srcs)
    records = []
    for path in paths:
        info = probe(path)
        v = next(s for s in info["streams"] if s["codec_type"] == "video")
        dims = (v["width"], v["height"])
        expected_dims = (80, 60) if tool == "cropVideo" else (160, 120)
        if tool == "compress" and source.suffix.lower() == ".gif":
            expected_dims = (48, 36)
        assert dims == expected_dims, f"dimensions {dims} != {expected_dims}"
        audio = [s for s in info["streams"] if s["codec_type"] == "audio"]
        expect_audio = source.suffix.lower() != ".gif" and tool != "muteVideo"
        assert bool(audio) == expect_audio
        # WMAV2/ASF pads whole codec blocks (~0.1 s per clip); inspect decoded
        # audio too, not just a permissive duration check. Other formats get 0.18s.
        tolerance = 0.25 if source.suffix.lower() == ".wmv" else 0.18
        near(float(info["format"]["duration"]), expected_duration, tolerance)
        run(["ffmpeg", "-v", "error", "-i", str(path), "-f", "null", "-"])
        if tool == "changeVideoSpeed" and audio:
            near(len(pcm(path)) / 16000, 0.6, tolerance)
        if tool == "redactVideo":
            frame = run(
                [
                    "ffmpeg",
                    "-v",
                    "error",
                    "-i",
                    str(path),
                    "-frames:v",
                    "1",
                    "-f",
                    "rawvideo",
                    "-pix_fmt",
                    "rgb24",
                    "-",
                ]
            ).stdout
            assert len(frame) == 160 * 120 * 3 and max(frame) < 10
        if tool == "removeMetadata":
            assert before["format"].get("tags", {}).get("title"), "fixture title missing"
            for section in [info["format"], *info["streams"]]:
                assert not section.get("tags", {}).get("title"), "title survived"
        if tool == "compress":
            assert path.stat().st_size < source.stat().st_size, (
                "media did not get smaller"
            )
        records.append(
            {
                "dimensions": list(dims),
                "duration": float(info["format"]["duration"]),
                "audio": bool(audio),
            }
        )
    if tool == "splitVideo":
        assert len(paths) == 2 * len(srcs), "wrong segment count"
    return {"media": records, "decoded": True}


def audio_effect(tool, srcs, paths):
    records = []
    for src, path in zip(srcs, paths, strict=True):
        info = probe(path)
        a = next(s for s in info["streams"] if s["codec_type"] == "audio")
        expected = 0.6 if tool == "trimAudio" else 1.2
        near(float(info["format"]["duration"]), expected)
        samples, original = pcm(path), pcm(src)
        assert rms(samples) > 0.001, "silent output"
        if tool == "audioChannels":
            assert (
                next(s for s in probe(src)["streams"] if s["codec_type"] == "audio")[
                    "channels"
                ]
                == 2
            )
            assert a["channels"] == 1
        elif tool == "normalizeAudio":
            assert rms(samples) > rms(original) * 1.2, (
                "normalization has no measurable gain"
            )
        elif tool == "redactAudio":
            # The inserted tone must dominate at 1 kHz, replacing the 440 Hz input.
            window = samples[8000:12000]

            def power(freq, window=window):
                return abs(
                    sum(
                        x
                        * complex(
                            math.cos(2 * math.pi * freq * n / 16000),
                            math.sin(2 * math.pi * freq * n / 16000),
                        )
                        for n, x in enumerate(window)
                    )
                )

            assert power(1000) > power(440) * 10
            near(rms(samples[1000:3000]), rms(original[1000:3000]), 0.01)
        elif tool == "audioToVideo":
            v = next(s for s in info["streams"] if s["codec_type"] == "video")
            assert (v["width"], v["height"]) == (320, 240)
            raw = run(
                [
                    "ffmpeg",
                    "-v",
                    "error",
                    "-i",
                    str(path),
                    "-frames:v",
                    "1",
                    "-f",
                    "rawvideo",
                    "-pix_fmt",
                    "rgb24",
                    "-",
                ]
            ).stdout
            assert max(raw) > 50 and len(set(raw)) > 5, "blank visualizer"
        elif tool == "removeMetadata":
            assert probe(src)["format"].get("tags", {}).get("title")
            assert not info["format"].get("tags", {}).get("title")
        elif tool == "compress":
            # WAV PCM can legitimately be incompressible; the explicit byte target
            # is independently enforced. FLAC must still decode identical samples.
            assert path.stat().st_size <= 1_000_000
            if src.suffix.lower() not in {".wav", ".flac"}:
                assert path.stat().st_size < src.stat().st_size
        records.append(
            {
                "duration": float(info["format"]["duration"]),
                "channels": a["channels"],
                "rms": rms(samples),
            }
        )
    return {"audio": records, "decoded": True}


def tool_cell(cell, srcs, dest):
    tool, key = cell["operation_id"], cell["source_key"]
    kwargs = validate_options(tool, RAW_OPTIONS.get(tool, {})) if tool in SCHEMAS else {}
    out = apply_tool(tool, srcs, dest, **kwargs)
    paths = out if isinstance(out, list) else [out]
    assert paths, "empty result list"
    assert len(set(paths)) == len(paths), "duplicate output paths in selection"
    assert all(p.exists() for p in paths), "returned nonexistent result"
    if tool == "extractArchive":
        members = []
        for path in paths:
            files = [p for p in path.rglob("*") if p.is_file()]
            assert files and all(p.read_bytes() == PAYLOAD for p in files)
            assert all(path.resolve() in p.resolve().parents for p in files)
            members.extend(str(p.relative_to(path)) for p in files)
        assert len(members) == len(srcs), "selection lost an archive or collided"
        evidence = {"members": members}
    elif tool == "createPDF":
        with fitz.open(out) as doc:
            assert len(doc) == len(srcs)
            assert all(len(set(p.get_pixmap().samples)) > 1 for p in doc)
        evidence = {"pages": len(srcs)}
    elif tool == "createCollage":
        with Image.open(out) as im:
            assert im.size == (256 * len(srcs), 256)
            assert ImageStat.Stat(im.convert("RGB")).mean[0] > 50
        evidence = {"dimensions": [256 * len(srcs), 256]}
    elif key in IMAGE_KEYS:
        assert len(paths) == len(srcs)
        evidence = {
            "images": [
                image_effect(tool, src, p) for src, p in zip(srcs, paths, strict=True)
            ]
        }
        if tool == "removeMetadata" and key == ".bmp":
            # BMP defines no EXIF/XMP/text fields, so there is nothing to strip.
            # The effect to prove: output decodes with the same pixels (checked
            # in image_effect) and smuggles no extra bytes past its declared size.
            for output in paths:
                raw = output.read_bytes()
                assert raw[:2] == b"BM", "output is not a BMP"
                assert int.from_bytes(raw[2:6], "little") == len(raw), (
                    "BMP carries bytes beyond its declared size"
                )
            evidence["bmp_declared_size_matches_file"] = True
            return (
                "PASS",
                "BMP has no descriptive-metadata fields; output decodes with the "
                "same pixels and carries no bytes beyond its declared size",
                evidence,
                paths,
            )
    elif key == ".pdf":
        evidence = pdf_effect(tool, srcs, paths)
    elif key in AUDIO_KEYS:
        evidence = audio_effect(tool, srcs, paths)
    elif tool == "videoSnapshots":
        with Image.open(out) as im:
            assert im.size == (160, 120) and max(ImageStat.Stat(im).var) > 1
        evidence = {"dimensions": [160, 120], "nonblank_frame": True}
    elif key == ".gif" and tool == "removeMetadata":
        assert len(paths) == len(srcs)
        for source, output in zip(srcs, paths, strict=True):
            with Image.open(source) as src, Image.open(output) as result:
                assert src.info.get("comment") and not result.info.get("comment")
                assert result.n_frames == src.n_frames
                assert (
                    sum(
                        result.seek(i) or result.info["duration"]
                        for i in range(result.n_frames)
                    )
                    == 1200
                )
        evidence = {"comment_removed": True, "animation_preserved": True}
    else:
        evidence = video_effect(tool, srcs, paths)
    return (
        "PASS",
        "Requested content/effect and source preservation checked",
        evidence,
        paths,
    )


def edge_cases(fixtures, root):
    """Fault injection and invalid input checks, separate from support totals."""
    from unittest.mock import patch

    results = []

    def exercise(ident, fn):
        try:
            evidence = fn()
            results.append(
                {
                    "id": ident,
                    "status": "PASS",
                    "reason": "Safety assertion passed",
                    "evidence": evidence,
                }
            )
        except BACKEND_ERRORS as exc:
            results.append(
                {"id": ident, "status": "UNSUPPORTED", "reason": error_text(exc)}
            )
        except Exception as exc:
            results.append({"id": ident, "status": "FAIL", "reason": error_text(exc)})

    available = [
        c
        for c in inventory()
        if c["kind"] == "tools"
        and c["source_key"] in fixtures
        and c["source_key"] != ".gif"
    ]
    for ident in TOOLS:
        cell = next(c for c in available if c["operation_id"] == ident)

        def corrupt(ident=ident, cell=cell):
            case = root / "corrupt" / ident
            case.mkdir(parents=True)
            src = case / ("broken" + cell["source_key"])
            src.write_bytes(b"deliberately invalid synthetic fixture\x00\xff")
            before = sha(src)
            opts = (
                validate_options(ident, RAW_OPTIONS.get(ident, {}))
                if ident in SCHEMAS
                else {}
            )
            try:
                apply_tool(ident, [src] * cell["selection_count"], case / "out", **opts)
            except BACKEND_ERRORS:
                raise
            except (ValueError, OSError, RuntimeError, subprocess.CalledProcessError):
                assert sha(src) == before
                return {"invalid_input_rejected": True, "source_preserved": True}
            raise AssertionError("corrupt input reported success")

        exercise(f"corrupt:{ident}", corrupt)

    for key in (".jpg", ".pdf", ".mp4", ".wav", ".gif"):

        def target(key=key):
            dest = root / "target" / key.lstrip(".")
            try:
                apply_tool("compress", [fixtures[key]], dest, max_bytes=16)
            except ValueError as exc:
                assert "target" in str(exc)
                assert not [p for p in dest.rglob("*") if p.is_file()]
                return {
                    "impossible_target_rejected": True,
                    "oversized_output_removed": True,
                }
            raise AssertionError("impossible 16-byte compression target reported success")

        exercise(f"compression-target:{key}", target)

    for ident, key, opts in [
        ("cropImage", ".png", {"box": (0, 0, 10000, 10000)}),
        ("cropVideo", ".mp4", {"box": (0, 0, 10000, 10000)}),
        ("trimVideo", ".mp4", {"start": 0.2, "end": 999}),
        ("trimAudio", ".wav", {"start": 0.2, "end": 999}),
        ("redactAudio", ".wav", {"start": 0.2, "end": 999}),
        ("videoSnapshots", ".mp4", {"at": 999}),
        ("editImage", ".png", {}),
        ("annotateImage", ".png", {}),
        ("redactImage", ".png", {}),
    ]:

        def invalid(ident=ident, key=key, opts=opts):
            try:
                apply_tool(ident, [fixtures[key]], root / "invalid" / ident, **opts)
            except ValueError as exc:
                return {"invalid_choice_rejected": True, "message": str(exc)}
            raise AssertionError("invalid choice reported success")

        exercise(f"invalid-choice:{ident}", invalid)

    for ident, key, opts in [
        ("trimVideo", ".mp4", {"start": 0, "end": 0.6}),
        ("normalizeAudio", ".flac", {}),
        ("audioToVideo", ".wav", {}),
    ]:

        def absent(ident=ident, key=key, opts=opts):
            with patch("shutil.which", return_value=None):
                try:
                    apply_tool(ident, [fixtures[key]], root / "missing" / ident, **opts)
                except BACKEND_ERRORS as exc:
                    assert "ffmpeg" in str(exc)
                    return {"simulated_absence": True, "actionable_error": str(exc)}
                raise AssertionError("missing ffmpeg reported success")

        exercise(f"missing-ffmpeg:{ident}", absent)

    for key, module, ident in [
        (".heic", "pillow_heif", "cropImage"),
        (".svg", "cairosvg", "createCollage"),
    ]:

        def absent_image(key=key, module=module, ident=ident):
            with patch.dict("sys.modules", {module: None}):
                try:
                    opts = {"box": (0, 0, 48, 32)} if ident == "cropImage" else {}
                    apply_tool(ident, [fixtures[key]], root / "missing" / module, **opts)
                except BACKEND_ERRORS as exc:
                    return {"simulated_absence": True, "actionable_error": str(exc)}
                raise AssertionError("missing optional image backend reported success")

        exercise(f"missing-image-backend:{module}", absent_image)
    return results


def totals(cells):
    counts = Counter(c["status"] for c in cells)
    return {s: counts[s] for s in ("PASS", "FAIL", "UNSUPPORTED", "UNTESTED")}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--json", type=Path)
    parser.add_argument("--work-dir", type=Path)
    args = parser.parse_args()
    root = args.work_dir or Path(tempfile.mkdtemp(prefix="kumquat-tools-sweep-"))
    root.mkdir(parents=True, exist_ok=True)
    if any(root.iterdir()):
        parser.error("--work-dir must be empty; existing files are never touched")
    started = time.monotonic()
    fixtures, fixture_errors = prepare(root / "fixtures")
    hashes = {key: sha(path) for key, path in fixtures.items()}
    cells = inventory()
    for index, cell in enumerate(cells):
        key, tool, count = (
            cell["source_key"],
            cell["operation_id"],
            cell["selection_count"],
        )
        if key not in fixtures:
            cell.update(
                status="UNTESTED", reason=fixture_errors.get(key, "No real fixture")
            )
        elif cell["kind"] == "actions" and tool != "move":
            requirements = {
                "copy": "wl-copy",
                "copy-path": "wl-copy",
                "float": "hyprctl",
                "share": "localsend-cli",
            }
            backend = requirements.get(tool)
            if backend and not shutil.which(backend):
                cell.update(
                    status="UNSUPPORTED", reason=f"Required executable {backend} absent"
                )
            else:
                cell.update(
                    status="UNTESTED",
                    reason={
                        "copy": (
                            "Real clipboard deliberately untouched; "
                            "payload unit tests only"
                        ),
                        "copy-path": (
                            "Real clipboard deliberately untouched; "
                            "payload unit tests only"
                        ),
                        "float": (
                            "User window/compositor deliberately untouched; "
                            "manifest unit tests do not prove a shelf"
                        ),
                        "share": (
                            "No real transfer/device picker invoked; argv unit tests only"
                        ),
                        "open-terminal": (
                            "No real desktop terminal invoked; spawn/cwd unit tests only"
                        ),
                    }[tool],
                )
        else:
            src = fixtures[key]
            case = root / "cases" / str(index)
            case.mkdir(parents=True)
            srcs = []
            for n in range(count):
                path = case / f"input {n} Ω {src.name}"
                shutil.copyfile(src, path)
                srcs.append(path)
            before = {p: sha(p) for p in srcs}
            try:
                if cell["kind"] == "actions":
                    dest = case / "moved"
                    # Exercise the exact pure options translation the GUI uses.
                    options = validate_options("move", {"destination": str(dest)})
                    outputs = actions.move_files(srcs, Path(options["destination"]))
                    assert len(outputs) == count
                    assert all(not p.exists() for p in srcs)
                    assert all(sha(p) == hashes[key] for p in outputs)
                    cell.update(
                        status="PASS",
                        reason="Only disposable copies moved; bytes/cardinality verified",
                        evidence={
                            "disposable_copies_only": True,
                            "moved_count": len(outputs),
                        },
                    )
                else:
                    # Beside-source writes replicate the real tool dispatcher.
                    status, reason, evidence, paths = tool_cell(cell, srcs, case)
                    saved = {p: sha(p) for p in paths if p.is_file()}
                    # Repeat EVERY tool cell: collisions must preserve earlier bytes.
                    _, _, _, second = tool_cell(cell, srcs, case)
                    assert set(paths).isdisjoint(second), "repeat reused output path"
                    assert all(sha(p) == digest for p, digest in saved.items()), (
                        "prior output overwritten"
                    )
                    assert all(sha(p) == digest for p, digest in before.items()), (
                        "source modified"
                    )
                    cell.update(
                        status=status,
                        reason=reason,
                        evidence={
                            **evidence,
                            "source_preserved": True,
                            "collision_safe": True,
                            "options": validate_options(tool, RAW_OPTIONS.get(tool, {}))
                            if tool in SCHEMAS
                            else {},
                        },
                    )
            except BACKEND_ERRORS as exc:
                cell.update(status="UNSUPPORTED", reason=error_text(exc))
            except NotImplementedError as exc:
                cell.update(status="UNSUPPORTED", reason=error_text(exc))
            except Exception as exc:
                cell.update(status="FAIL", reason=error_text(exc))
            if cell["kind"] == "tools" and any(
                not p.is_file() or sha(p) != value for p, value in before.items()
            ):
                cell.update(status="FAIL", reason="SOURCE MODIFIED")
        print(cell["status"], cell["id"], cell["reason"], flush=True)
    edges = edge_cases(fixtures, root / "edges")
    for edge in edges:
        print(edge["status"], edge["id"], edge["reason"], flush=True)
    preserved = all(sha(path) == hashes[key] for key, path in fixtures.items())
    by_id = {
        ident: totals([c for c in cells if c["operation_id"] == ident])
        for ident in [*TOOLS, *ACTIONS]
    }
    reasons = defaultdict(list)
    for cell in cells + edges:
        if cell["status"] != "PASS":
            reasons[f"{cell['status']}: {cell['reason']}"].append(cell["id"])
    report = {
        "schema_version": 1,
        "scope": "Backend effects plus pure options schemas, not live GTK/desktop",
        "tool_ids": TOOLS,
        "action_ids": ACTIONS,
        "cell_count": len(cells),
        "totals": totals(cells),
        "tool_totals": totals([c for c in cells if c["kind"] == "tools"]),
        "action_totals": totals([c for c in cells if c["kind"] == "actions"]),
        "by_operation": by_id,
        "source_preservation": preserved,
        "fixture_hashes": hashes,
        "fixture_errors": fixture_errors,
        "cells": cells,
        "edges": edges,
        "edge_totals": totals(edges),
        "nonpass_by_reason": dict(reasons),
        "elapsed_seconds": round(time.monotonic() - started, 2),
    }
    result = args.json or root / "tools-results.json"
    result.parent.mkdir(parents=True, exist_ok=True)
    result.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(
        json.dumps(
            {
                k: report[k]
                for k in (
                    "cell_count",
                    "totals",
                    "tool_totals",
                    "action_totals",
                    "edge_totals",
                    "source_preservation",
                )
            },
            indent=2,
        )
    )
    print("JSON:", result)
    return int(not preserved or any(c["status"] == "FAIL" for c in cells + edges))


